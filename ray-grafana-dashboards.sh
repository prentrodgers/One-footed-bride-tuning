#!/usr/bin/env bash
# ray-grafana-dashboards.sh — load Ray's Grafana dashboards into Grafana.
#
#     ./ray-grafana-dashboards.sh          # needs a running `tuning` RayCluster
#
# Ray generates its dashboards (JSON) on the head at start-up, matching the
# metrics that Ray version emits.  This copies them out of the head and
# applies them as a ConfigMap in the prometheus namespace with the
# grafana_dashboard=1 label, which kube-prometheus-stack's Grafana sidecar
# watches — the same mechanism k8s-grafana-dashboards.yaml uses.  They show
# up in Grafana under the "Ray" folder within a minute.
#
# Nothing here is committed: the JSON is Ray's, not ours, and is regenerated
# whenever Ray is bumped (parallel-jobs/Containerfile RAY_VER) — re-run this
# after the first cluster on a new Ray version.  The scrape side is
# k8s-ray-monitoring.yaml.
#
# Only the default dashboard is loaded.  Ray also writes Data, Serve, Train
# and LLM dashboards; nothing here uses those libraries, so they are empty
# (Data was loaded until 11 Oct 2026 and never showed anything).
#
# One panel of ours is added to it: CPU package temperature per node, from
# node-exporter (the same query as the fleet panel in grafana/make_dashboards.py),
# under "Hardware Utilization by Node" after the two Node CPU panels.
set -euo pipefail
HEAD=$(kubectl get pod -l ray.io/cluster=tuning,ray.io/node-type=head -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)
[ -n "$HEAD" ] || { echo "no tuning RayCluster is running (the dashboards are generated by the head)" >&2; exit 1; }
SRC=/tmp/ray/session_latest/metrics/grafana/dashboards
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# Ray titles it "Default Dashboard", which says nothing next to the other
# dashboards in Grafana: prefix the title and tag it, leaving the uid
# (rayDefaultDashboard) alone since the Ray dashboard's Metrics tab embeds
# panels by uid.
for f in default_grafana_dashboard.json; do
    kubectl exec "$HEAD" -c ray-head -- cat "$SRC/$f" \
      | python3 -c '
import json, sys
d = json.load(sys.stdin)
d["title"] = "Ray: " + d["title"].replace(" Dashboard", "").lower()
d["tags"] = sorted(set(d.get("tags", []) + ["ray", "one-footed-bride"]))

# The temperature panel: full width, directly under Node CPU Usage / Usage %;
# everything from there down moves 8 rows to make room.
cpu = next(p for p in d["panels"] if p.get("title") == "Node CPU Usage %")
y = cpu["gridPos"]["y"] + cpu["gridPos"]["h"]
for p in d["panels"] + [q for r in d["panels"] for q in r.get("panels", [])]:   # incl. collapsed rows
    if p["gridPos"]["y"] >= y:
        p["gridPos"]["y"] += 8
uname = "* on(instance) group_left(nodename) node_uname_info{nodename=~\"fs[0-9]\"}"
d["panels"].append({
    "id": 9001, "type": "timeseries", "title": "CPU package temperature",
    "description": "Hottest CPU package sensor per node (node-exporter hwmon: Package id 0 on Intel, Tctl on Ryzen). Not filtered by the dashboard variables.",
    "datasource": "${datasource}",
    "gridPos": {"x": 0, "y": y, "w": 24, "h": 8},
    "targets": [{"refId": "A", "legendFormat": "{{nodename}}",
                 "expr": "max by (nodename) ((node_hwmon_temp_celsius * on(chip,sensor,instance) group_left(label) "
                         "node_hwmon_sensor_label{label=~\"Package id 0|Tctl\"}) " + uname + ")"}],
    "fieldConfig": {"defaults": {"unit": "celsius", "min": 20, "max": 100,
        "thresholds": {"mode": "absolute", "steps": [{"color": "green", "value": None},
                                                     {"color": "orange", "value": 75},
                                                     {"color": "red", "value": 85}]},
        "custom": {"lineWidth": 1, "fillOpacity": 12, "showPoints": "never",
                   "thresholdsStyle": {"mode": "line"}}}, "overrides": []},
    "options": {"legend": {"displayMode": "table", "placement": "right", "showLegend": True,
                           "calcs": ["lastNotNull", "max"]},
                "tooltip": {"mode": "multi", "sort": "desc"}}})
d["panels"].sort(key=lambda p: (p["gridPos"]["y"], p["gridPos"]["x"]))
json.dump(d, sys.stdout, indent=1)
n, uid, title = len(d["panels"]), d["uid"], d["title"]
print(f"{sys.argv[1]:<32} {n} panels, uid {uid}, title {title!r}", file=sys.stderr)
' "$f" > "$TMP/ray-$f"
done

# Server-side apply: the dashboard JSON is more than the 256 KiB a
# client-side apply can stash in its last-applied annotation.  It also drops
# keys this script no longer writes (the Data dashboard).
kubectl create configmap ray-dashboards -n prometheus \
    --from-file="$TMP" --dry-run=client -o yaml \
  | kubectl label --local -f - grafana_dashboard=1 app=ray-tuning -o yaml \
  | kubectl apply --server-side --force-conflicts -f -
echo "Grafana's sidecar loads them within ~60s: http://<any node>:30814, search \"Ray:\""
